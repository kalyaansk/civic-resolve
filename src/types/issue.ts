/**
 * Core domain types for the CivicResolve civic issue tracking and triage platform.
 */

export const ISSUE_STATUSES = [
  "Reported",
  "In Progress",
  "Pending Verification",
  "Resolved",
] as const;
export type IssueStatus = (typeof ISSUE_STATUSES)[number];

export const COMPLETION_VERDICTS = [
  "Verified Fixed",
  "Partially Fixed",
  "Needs Re-Inspection",
] as const;
export type CompletionVerdict = (typeof COMPLETION_VERDICTS)[number];

export const COMPLETION_RECOMMENDED_ACTIONS = [
  "Approve Resolution",
  "Request Rework",
] as const;
export type CompletionRecommendedAction =
  (typeof COMPLETION_RECOMMENDED_ACTIONS)[number];

export const ISSUE_PRIORITIES = ["Critical", "High", "Medium", "Low"] as const;
export type IssuePriority = (typeof ISSUE_PRIORITIES)[number];

export const ISSUE_CATEGORIES = [
  "Road Infrastructure",
  "Street Lighting",
  "Sanitation & Waste",
  "Water & Drainage",
  "Parks & Forestry",
  "Traffic & Signals",
  "Sidewalks & Accessibility",
  "Public Safety & Hazards",
] as const;
export type IssueCategory = (typeof ISSUE_CATEGORIES)[number];

export const MUNICIPAL_DEPARTMENTS = [
  "Public Works — Road Maintenance",
  "Street Lighting & Power",
  "Sanitation & Solid Waste",
  "Water & Drainage",
  "Parks & Forestry",
  "Transportation & Traffic Engineering",
  "Public Safety & Code Enforcement",
] as const;
export type MunicipalDepartment = (typeof MUNICIPAL_DEPARTMENTS)[number];

/** Structured multimodal triage result generated by Gemini AI or the deterministic fallback. */
export interface AIAnalysis {
  category: IssueCategory;
  confidence: number;
  priority: IssuePriority;
  urgencyScore: number;
  recommendedDepartment: MunicipalDepartment;
  estimatedImpact: string;
  reasoning: string;
  imageAltText: string;
  source: "gemini" | "fallback";
  model: string;
  /** False when the report is off-topic, spam, or fails civic relevance validation. */
  isValidCivicIssue?: boolean;
  /** True when prompt-injection or instruction-override attempts were detected. */
  promptInjectionDetected?: boolean;
  /** Human-readable explanation when a report is rejected as off-topic or injected. */
  rejectionReason?: string | null;
}

export type GeminiTriageResult = AIAnalysis;

/** Gemini AI before-vs-after repair completion verification result. */
export interface CompletionVerification {
  verified: boolean;
  verdict: CompletionVerdict;
  confidence: number;
  summary: string;
  recommendedAction: CompletionRecommendedAction;
  model: string;
  source: "gemini" | "fallback";
  analyzedAt: string;
}

/** Field worker proof-of-completion submission awaiting or approved by Authority. */
export interface CompletionReport {
  afterPhotoUrl: string;
  workerUid: string;
  workerName: string;
  workerNote: string;
  submittedAt: string;
  aiVerification: CompletionVerification;
}

/** Single immutable entry in a complaint's public status timeline. */
export interface StatusHistoryEntry {
  status: IssueStatus;
  timestamp: string;
  note: string;
  updatedBy: string;
}

/** Geographic coordinates and localized address hierarchy for a civic report. */
export interface IssueLocation {
  address: string;
  city: string;
  state: string;
  district: string;
  lat: number;
  lng: number;
}

/** Complete civic issue record stored in Firestore and returned by public/private APIs. */
export interface Issue {
  id: string;
  referenceCode: string;
  title: string;
  description: string;
  category: IssueCategory;
  status: IssueStatus;
  priority: IssuePriority;
  urgencyScore: number;
  department: MunicipalDepartment;
  state: string;
  city: string;
  location: IssueLocation;
  photoUrl: string | null;
  photoAltText: string;
  upvotes: number;
  upvotedBy: string[];
  reporterUid: string | null;
  reporterName: string;
  resolutionNote: string | null;
  completionReport?: CompletionReport | null;
  aiAnalysis: AIAnalysis;
  statusHistory: StatusHistoryEntry[];
  createdAt: string;
  updatedAt: string;
}

/** Aggregate KPI summary counts displayed on public and authority dashboards. */
export interface DashboardStats {
  total: number;
  reported: number;
  inProgress: number;
  pendingVerification: number;
  resolved: number;
  critical: number;
  resolutionRate: number;
}

/** Paginated API response returned by GET /api/issues. */
export interface PaginatedIssuesResponse {
  issues: Issue[];
  total: number;
  hasMore: boolean;
  nextCursor: string | null;
  stats: DashboardStats;
}

/** Supported 3-tier CivicResolve roles. */
export type UserRole = "citizen" | "worker" | "authority";

/** Authenticated user profile supporting strict 3-tier CivicResolve RBAC. */
export interface UserProfile {
  uid: string;
  email: string;
  displayName: string;
  role: UserRole;
  isDemo?: boolean;
}
